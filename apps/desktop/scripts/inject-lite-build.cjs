#!/usr/bin/env node
/**
 * Toggle the desktop LITE flag (mirrors inject-relay-token.cjs): the
 * packaged app can't read env, so the flag is compiled in. `node
 * inject-lite-build.cjs 1` before a Lite build; `0` restores the
 * committed byte-for-byte default. Lite main: no update checks, no
 * pairing/relay IPC, no voice-model downloads, and a session-level
 * blocker that cancels every http(s)/ws request from the renderer.
 */
const fs = require('node:fs');
const path = require('node:path');
const on = process.argv[2] === '1';
const out = path.join(__dirname, '..', 'src', 'lite-build.ts');
fs.writeFileSync(
  out,
  '// AUTO-GENERATED by scripts/inject-lite-build.cjs — do not edit.\n' +
    `export const LITE_BUILD = ${on};\n`,
);
console.log(`[inject-lite-build] LITE_BUILD = ${on}`);
